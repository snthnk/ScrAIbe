TAG_VOCABULARY: Tuple[str, ...] = tuple(TAG_KEYWORDS)

_WORD_RE = re.compile(r"[а-яёА-ЯЁ-]+")


@lru_cache(maxsize=1)
def _morph():
    try:
        import pymorphy3

        return pymorphy3.MorphAnalyzer()
    except Exception:  # pragma: no cover - морфология необязательна
        return None


@lru_cache(maxsize=4096)
def _lemma(word: str) -> str:
    word = word.lower().replace("ё", "е")
    morph = _morph()
    if morph is None:
        return word[:6]
    return morph.parse(word)[0].normal_form.replace("ё", "е")


@lru_cache(maxsize=1)
def _keyword_index() -> Dict[str, Set[str]]:
    index: Dict[str, Set[str]] = {}
    for tag, words in TAG_KEYWORDS.items():
        for word in words:
            index.setdefault(_lemma(word), set()).add(tag)
    return index


def extract_tags(query: str, max_tags: int = 5) -> List[str]:
    """Темы из словаря, ключевые слова которых встретились в запросе (порядок — по числу совпадений)."""
    index = _keyword_index()
    counts: Dict[str, int] = {}
    for token in _WORD_RE.findall(query or ""):
        for tag in index.get(_lemma(token), ()):
            counts[tag] = counts.get(tag, 0) + 1
    ranked = sorted(counts.items(), key=lambda item: (-item[1], list(TAG_KEYWORDS).index(item[0])))
    return [tag for tag, _ in ranked[:max_tags]]


def normalize_tags(tags: Iterable[str]) -> List[str]:
    """Явно переданные теги -> нижний регистр, без дублей."""
    result: List[str] = []
    for tag in tags or []:
        value = str(tag).strip().lower()
        if value and value not in result:
            result.append(value)
    return result


def unknown_tags(tags: Sequence[str]) -> List[str]:
    return [t for t in tags if t not in TAG_KEYWORDS]
